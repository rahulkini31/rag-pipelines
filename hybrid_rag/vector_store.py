"""Qdrant Cloud hybrid vector store setup."""

from typing import List

from langchain_core.documents import Document
from langchain_openai import OpenAIEmbeddings
from langchain_qdrant import FastEmbedSparse, QdrantVectorStore, RetrievalMode
from qdrant_client import QdrantClient, models

from .config import Settings
from .reranker import Qwen3CrossEncoderReranker


class Qwen3FeatherlessEmbeddings(OpenAIEmbeddings):
    """Use Featherless for Qwen embeddings with query-only instruction formatting."""

    query_instruction: str = (
        "Instruct: Given a technical search query, retrieve relevant document passages "
        "that answer the query\nQuery: "
    )

    def embed_query(self, text: str) -> List[float]:
        formatted_query = f"{self.query_instruction}{text}"
        return super().embed_query(formatted_query)


class HybridVectorStore:
    def __init__(self, settings: Settings, collection_name: str, dense_dim: int = 4096):
        # Store the logical name of the Qdrant collection for this tenant or document set.
        self.collection_name = collection_name
        self.reranker = Qwen3CrossEncoderReranker()

        # Connect to the Qdrant Cloud instance using the configured URL and API key.
        self.client = QdrantClient(
            url=settings.qdrant_url,
            api_key=settings.qdrant_api_key,
            timeout=60,
        )

        # Ensure the collection exists before using it, then create the LangChain wrapper.
        self._ensure_collection(dense_dim)
        self.store = QdrantVectorStore(
            client=self.client,
            collection_name=collection_name,
            # Dense embeddings are generated by Featherless through its OpenAI-compatible API.
            embedding=Qwen3FeatherlessEmbeddings(
                model=settings.embedding_model,
                api_key=settings.featherless_api_key,
                base_url=settings.featherless_base_url,
                check_embedding_ctx_length=False,
                chunk_size=32,
            ),
            # Sparse BM25 embeddings enable lexical matching alongside vector similarity.
            sparse_embedding=FastEmbedSparse(model_name="Qdrant/bm25"),
            retrieval_mode=RetrievalMode.HYBRID,
            vector_name="dense",
            sparse_vector_name="sparse_bm25",
        )

    def rerank_documents(
        self,
        query: str,
        candidate_k: int = 20,
        top_k: int = 5,
        filter: models.Filter | None = None,
    ) -> list[tuple[Document, float]]:
        """Retrieve hybrid candidates from Qdrant and rerank them with Featherless."""
        candidates = self.store.similarity_search(
            query=query,
            k=candidate_k,
            filter=filter,
        )
        return self.reranker.rerank(query, candidates, top_k=top_k)

    def _ensure_collection(self, dense_dim: int) -> None:
        # Skip setup if the collection has already been created for this environment.
        if self.client.collection_exists(self.collection_name):
            return

        # Create a hybrid collection with a dense vector index and a sparse BM25 index.
        self.client.create_collection(
            collection_name=self.collection_name,
            vectors_config={
                "dense": models.VectorParams(
                    size=dense_dim,
                    distance=models.Distance.COSINE,
                    on_disk=True,
                )
            },
            quantization_config=models.ScalarQuantization(
                scalar=models.ScalarQuantizationConfig(
                    type=models.ScalarType.INT8,
                    quantile=0.99,
                    always_ram=True,
                )
            ),
            sparse_vectors_config={
                "sparse_bm25": models.SparseVectorParams(modifier=models.Modifier.IDF)
            },
        )

        # Add fast metadata filters for tenant and document-level retrieval.
        for field in ("metadata.tenant_id", "metadata.doc_id"):
            self.client.create_payload_index(
                collection_name=self.collection_name,
                field_name=field,
                field_schema=models.PayloadSchemaType.KEYWORD,
            )

        # Keep document version available as a numeric filter for updates or reindexing.
        self.client.create_payload_index(
            collection_name=self.collection_name,
            field_name="metadata.doc_version",
            field_schema=models.PayloadSchemaType.INTEGER,
        )